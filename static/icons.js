  // Shorter drawings sit in the middle of the 12x12 square.
  function square(rows) {
    const out = rows.map((r) => r.padEnd(12, ".").slice(0, 12));
    const top = Math.floor((12 - out.length) / 2);
    return [...Array(top).fill("............"), ...out, ...Array(Math.max(0, 12 - top - out.length)).fill("............")];
  }

  function svg(rows) {
    let rects = "";
    square(rows).forEach((row, y) => {
      let x = 0;
      while (x < 12) {
        if (row[x] !== "#") { x++; continue; }
        const start = x;
        while (x < 12 && row[x] === "#") x++;
        rects += `<rect x='${start}' y='${y}' width='${x - start}' height='1'/>`;
      }
    });
    return `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 12 12' shape-rendering='crispEdges'>${rects}</svg>`;
  }

  const css = Object.entries(ICONS)
    .map(([name, rows]) => `.ico-${name}{--ico:url("data:image/svg+xml,${encodeURIComponent(svg(rows))}")}`)
    .join("\n");
  const style = document.createElement("style");
  style.id = "px-icons";
  style.textContent = css;
  document.head.append(style);

  function el(name, extra = "") {
    const i = document.createElement("i");
    i.className = `ico ico-${name}${extra ? ` ${extra}` : ""}`;
    i.setAttribute("aria-hidden", "true");
    return i;
  }

  window.Icons = { el, names: Object.keys(ICONS) };
